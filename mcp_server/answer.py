"""Grounded answer generation with citations.

If OLLAMA_URL points at a model server inside the boundary (e.g. a local Ollama or a
private Bedrock-compatible endpoint), the answer is generated by that model and
must cite the numbered sources. Otherwise an extractive answer is assembled from
the highest-scoring sentences, so the system stays deterministic and testable
without any model at all.
"""

from __future__ import annotations

import os
import re

import httpx

from .retrieval import Hit, tokenize

_SENT = re.compile(r"(?<=[.!?])\s+")
_CITE = re.compile(r"\[(\d+)\]")


def extractive_answer(query: str, hits: list[Hit], max_sentences: int = 3) -> str:
    terms = set(tokenize(query))
    scored: list[tuple[float, int, str]] = []
    for idx, hit in enumerate(hits, start=1):
        for sent in _SENT.split(hit.chunk.text):
            overlap = len(terms & set(tokenize(sent)))
            if overlap:
                scored.append((overlap + hit.score / 100, idx, sent.strip()))
    scored.sort(key=lambda t: t[0], reverse=True)
    picked, seen = [], set()
    for _, idx, sent in scored:
        if sent not in seen:
            picked.append(f"{sent} [{idx}]")
            seen.add(sent)
        if len(picked) == max_sentences:
            break
    return " ".join(picked)


def llm_answer(query: str, hits: list[Hit], base_url: str, model: str) -> str:
    context = "\n".join(f"[{i}] ({h.chunk.source} / {h.chunk.section}) {h.chunk.text}" for i, h in enumerate(hits, 1))
    prompt = (
        "Answer the question using only the numbered sources. Cite every claim with its source "
        "number in square brackets, like [1]. If the sources do not contain the answer, say so.\n\n"
        f"Sources:\n{context}\n\nQuestion: {query}\nAnswer:"
    )
    resp = httpx.post(f"{base_url.rstrip('/')}/api/generate", json={"model": model, "prompt": prompt, "stream": False}, timeout=60)
    resp.raise_for_status()
    return resp.json()["response"].strip()


def cited_ids(answer: str) -> set[int]:
    return {int(n) for n in _CITE.findall(answer)}


def answer(query: str, hits: list[Hit]) -> tuple[str, str]:
    """Return (answer_text, generator_name)."""
    if not hits:
        return "No supporting documents were found for this question.", "none"
    base = os.getenv("OLLAMA_URL")
    if base:
        return llm_answer(query, hits, base, os.getenv("OLLAMA_MODEL", "llama3.2")), "ollama"
    return extractive_answer(query, hits), "extractive"
